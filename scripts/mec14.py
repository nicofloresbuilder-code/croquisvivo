import re, sys
from playwright.sync_api import sync_playwright
H=sys.argv[1] if len(sys.argv)>1 else "http://localhost:3140"
ok=0; mal=0; errs=[]
def t(n,c,extra=""):
    global ok,mal
    if c: ok+=1
    else: mal+=1
    print(("OK   " if c else "MAL  ")+n+(("  "+str(extra)) if extra else ""))
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/opt/pw-browsers/chromium")
    ctx=b.new_context(viewport={"width":1200,"height":900},accept_downloads=True); pg=ctx.new_page()
    pg.on("pageerror",lambda e:errs.append("pageerror "+str(e))); pg.on("console",lambda m: errs.append(m.text) if m.type=="error" else None)
    r=pg.goto(H+"/pricing"); pg.wait_for_timeout(900)
    cu=pg.inner_text("body"); low=cu.lower()
    t("/pricing carga",r.status==200 and "Precios" in pg.title())
    t("aviso: precio de prueba, hipótesis, nadie ha pagado","hipótesis no validada" in low and "nadie ha pagado" in low)
    t("tres planes", all(pg.locator(i).count()==1 for i in ["#plan-libre","#plan-inmueble","#plan-institucion"]))
    t("dos segmentos nombrados","segmento a" in low and "segmento b" in low)
    t("cada precio dice hipótesis", pg.locator("#plan-inmueble").inner_text().lower().count("hipótesis")>=1 and pg.locator("#plan-institucion").inner_text().lower().count("hipótesis")>=1)
    t("las funciones de pago dicen por construir", "por construir" in pg.locator("#plan-inmueble").inner_text().lower())
    t("línea gratis/pago: hallazgos siempre gratis","nunca están detrás de un pago" in cu)
    t("no vende veredicto","nunca se vende" in low and "no es una certificación" in low)
    t("no dice 'seguro' ni 'verificado' como resultado", not re.search(r"\b(es seguro|está seguro|verificado por)\b", low))
    t("la nav tiene Precios", pg.get_by_role("link",name="Precios").count()>=1)
    t("cita fuentes (Capterra, G2, Excélsior)", all(x in pg.content() for x in ["capterra.com","g2.com","excelsior.com.mx"]))
    # simulador por defecto
    res=pg.inner_text("#sim-resultado")
    t("simulador: 10 pagantes", "10" in res and "pagantes" in res)
    t("simulador: ingreso anual $30,000", re.search(r"\$\s?30,000",res) is not None, res[:200])
    t("simulador: ingreso mensual $2,500", re.search(r"\$\s?2,500",res) is not None)
    t("sin costo de entrega el margen dice por medir", "por medir" in res.lower())
    t("10:1 sin dato dice por medir y el umbral", "por medir" in res.lower() and re.search(r"\$\s?30,000",res) is not None)
    # cambiar segmento cambia el precio
    pg.select_option("#sim-seg","B"); pg.wait_for_timeout(200)
    t("segmento B pone precio 9000", pg.input_value("#sim-pre")=="9000")
    t("B: ingreso anual $90,000", re.search(r"\$\s?90,000",pg.inner_text("#sim-resultado")) is not None)
    pg.select_option("#sim-seg","A")
    # costos dan margen y razón
    pg.fill("#sim-ent","1000"); pg.fill("#sim-fij","1000"); pg.fill("#sim-act","45000"); pg.wait_for_timeout(200)
    res=pg.inner_text("#sim-resultado")
    t("margen $8,000", re.search(r"\$\s?8,000",res) is not None, res)
    t("equilibrio 6 pagantes", "6 pagantes" in res)
    t("razón 15 a 1 con tus datos", "15 a 1" in res and "no una medida" in res.lower())
    pg.fill("#sim-act","20000"); pg.wait_for_timeout(200)
    t("razón 6.67 no cumple", "no cumple" in pg.inner_text("#sim-resultado"))
    # entradas inválidas
    pg.fill("#sim-con","150"); pg.wait_for_timeout(200)
    t("conversión 150 da error y oculta resultados", pg.locator("#sim-errores").count()==1 and pg.locator("#sim-resultado").count()==0)
    pg.fill("#sim-con","abc"); pg.wait_for_timeout(200)
    t("conversión con letras da error", pg.locator("#sim-errores").count()==1)
    pg.fill("#sim-con","2,5"); pg.wait_for_timeout(200)
    t("conversión 2,5 se rechaza, no se lee como 25", pg.locator("#sim-errores").count()==1 and pg.locator("#sim-resultado").count()==0)
    pg.fill("#sim-con","2.5"); pg.wait_for_timeout(200)
    t("conversión 2.5 da 5 pagantes de 200", pg.inner_text("#sim-resultado").split("\n")[0].strip()=="5")
    pg.fill("#sim-con","5"); pg.fill("#sim-alc","10.5"); pg.wait_for_timeout(200)
    t("inmuebles con decimales da error", "entero" in pg.inner_text("#sim-errores"))
    pg.fill("#sim-alc","200"); pg.fill("#sim-ent",""); pg.fill("#sim-act",""); pg.fill("#sim-fij","0"); pg.wait_for_timeout(200)
    # guardar
    pg.get_by_role("button",name="Guardar escenario").click(); pg.wait_for_timeout(300)
    t("guardar sin nombre da error", "nombre" in pg.inner_text("#sim-guardar-errores").lower())
    pg.fill("#sim-nom","escribe a nico@correo.com"); pg.get_by_role("button",name="Guardar escenario").click(); pg.wait_for_timeout(300)
    t("nombre con correo rechazado", "correo" in pg.inner_text("#sim-guardar-errores").lower())
    pg.fill("#sim-nom","escuelas, conversión baja"); pg.get_by_role("button",name="Guardar escenario").click(); pg.wait_for_timeout(900)
    t("escenario guardado aparece", "escuelas, conversión baja" in pg.inner_text("#sim-guardados"))
    t("dice dónde se guardó", "guardado" in pg.inner_text("#sim-aviso").lower())
    pg.reload(); pg.wait_for_timeout(1000)
    t("persiste tras recargar", "escuelas, conversión baja" in pg.inner_text("#sim-guardados"))
    # cargar otro y cargar el guardado
    pg.fill("#sim-alc","1"); pg.wait_for_timeout(100)
    pg.get_by_role("button",name="Cargar escuelas, conversión baja").click(); pg.wait_for_timeout(200)
    t("cargar restaura los valores", pg.input_value("#sim-alc")=="200" and pg.input_value("#sim-con")=="5")
    # nombre fórmula + exportar
    pg.fill("#sim-nom","=1+1"); pg.get_by_role("button",name="Guardar escenario").click(); pg.wait_for_timeout(700)
    with pg.expect_download() as d: pg.get_by_role("button",name="Exportar CSV").first.click()
    csv=open(d.value.path(),encoding="utf-8").read()
    t("CSV exportado protege fórmula", "\"'=1+1\"" in csv and "por medir" in csv, csv[:200])
    pg.get_by_role("button",name="Borrar =1+1").click(); pg.wait_for_timeout(500)
    t("borrar quita el escenario", "=1+1" not in pg.inner_text("#sim-guardados"))
    # /about memo
    pg.goto(H+"/about#memo"); pg.wait_for_timeout(500); ab=pg.inner_text("body")
    t("memo: no afirma un 10:1 medido","no existe un 10:1 medido" in ab.lower())
    t("memo: tres costos con estado","sin dato" in ab.lower() and "por medir" in ab.lower() and "no verificado" in ab.lower())
    t("memo: umbral $30,000 y $90,000", "$30,000" in ab and "$90,000" in ab)
    t("memo: tres salidas honestas","bajar el precio" in ab.lower())
    t("memo: precios inventados", "inventados" in ab.lower())
    # conversaciones
    pg.goto(H+"/sesiones"); pg.wait_for_timeout(1000)
    cu=pg.inner_text("#conv-resumen")
    t("conversaciones: 0 y demanda 0", "0" in cu and "hipótesis" in pg.inner_text("#conversaciones").lower() or "Todavía no hay ninguna" in cu)
    t("no hay botón de borrar conversaciones", pg.locator("#conversaciones").get_by_role("button",name=re.compile("borrar",re.I)).count()==0)
    pg.get_by_role("button",name="Guardar conversación").click(); pg.wait_for_timeout(300)
    t("vacío da errores legibles", pg.locator("#conv-errores li").count()>=5)
    def llenar(res,cita="Se ve bien, lo platico con la dueña",paso="Llamar el lunes",costo="sin dato"):
        pg.select_option("#c-rol","director_escuela"); pg.select_option("#c-seg","A"); pg.select_option("#c-des","si")
        pg.fill("#c-tarea","Cuenta alumnos con cronómetro y firma una hoja"); pg.fill("#c-firma","Dueña del colegio"); pg.fill("#c-costo",costo)
        pg.fill("#c-precio","3,000"); pg.select_option("#c-res",res); pg.fill("#c-cita",cita); pg.fill("#c-paso",paso)
    llenar("interes_dicho",cita="llámame al 55 1234 5678"); pg.get_by_role("button",name="Guardar conversación").click(); pg.wait_for_timeout(300)
    t("cita con teléfono rechazada", "teléfono" in pg.inner_text("#conv-errores").lower())
    llenar("compromiso_firmado",paso="ok"); pg.get_by_role("button",name="Guardar conversación").click(); pg.wait_for_timeout(300)
    t("compromiso sin prueba rechazado", "prueba" in pg.inner_text("#conv-errores").lower())
    llenar("interes_dicho"); pg.get_by_role("button",name="Guardar conversación").click(); pg.wait_for_timeout(900)
    t("guardada y listada", "Se ve bien" in pg.inner_text("#conv-lista"))
    cu=pg.inner_text("#conv-resumen")
    t("interés dicho NO cuenta como demanda", re.search(r"0\s*demanda comprobada",cu.lower().replace("\n"," ")) is not None, cu)
    llenar("compromiso_firmado",paso="Carta de intención firmada el viernes",cita="Firmamos la carta"); pg.get_by_role("button",name="Guardar conversación").click(); pg.wait_for_timeout(900)
    cu=pg.inner_text("#conv-resumen").lower().replace("\n"," ")
    t("compromiso firmado sí cuenta (1)", re.search(r"1\s*demanda comprobada",cu) is not None, cu)
    pg.reload(); pg.wait_for_timeout(1000)
    t("conversaciones persisten", "Firmamos la carta" in pg.inner_text("#conv-lista"))
    # móvil sin scroll horizontal
    for ruta in ["/pricing","/about","/sesiones"]:
        m=b.new_context(viewport={"width":390,"height":800}).new_page(); m.goto(H+ruta); m.wait_for_timeout(700)
        sw=m.evaluate("document.documentElement.scrollWidth"); t(f"móvil {ruta} sin scroll horizontal", sw<=392, sw)
    t("sin errores de consola ni de página", not errs, errs[:3])
    b.close()
print(f"{ok} bien, {mal} mal"); sys.exit(1 if mal else 0)
